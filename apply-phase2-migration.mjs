async function run() {
  const conn = await mysql.createConnection(process.env.DATABASE_URL);
  for (let i = 0; i < tables.length; i++) {
    try {
      await conn.execute(tables[i]);
      const name = tables[i].match(/CREATE TABLE IF NOT EXISTS (\w+)/)?.[1];
      console.log(`✅ Created table: ${name}`);
    } catch (err) {
      console.error(`❌ Error on table ${i}:`, err.message);
    }
  }
  await conn.end();
  console.log('\\nAll Phase 2 tables created!');
}

run().catch(console.error);
